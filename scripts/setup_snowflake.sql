-- ==============================================================================
-- DataMind: Snowflake Setup Script (Run as ACCOUNTADMIN)
-- Sets up DATAMIND_WH, DATAMIND_DB.SALES with TPC-H tables, and read-only app role
-- ==============================================================================

USE ROLE ACCOUNTADMIN;

-- 1. Create dedicated Extra-Small Warehouse
CREATE WAREHOUSE IF NOT EXISTS DATAMIND_WH
    WITH WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

-- 2. Create Database and Schema
CREATE DATABASE IF NOT EXISTS DATAMIND_DB;
USE DATABASE DATAMIND_DB;

CREATE SCHEMA IF NOT EXISTS SALES;
USE SCHEMA SALES;

-- 3. Copy TPC-H tables from SNOWFLAKE_SAMPLE_DATA
CREATE TABLE IF NOT EXISTS CUSTOMER AS 
    SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.CUSTOMER;

CREATE TABLE IF NOT EXISTS ORDERS AS 
    SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS;

CREATE TABLE IF NOT EXISTS LINEITEM AS 
    SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.LINEITEM;

CREATE TABLE IF NOT EXISTS NATION AS 
    SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.NATION;

CREATE TABLE IF NOT EXISTS REGION AS 
    SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.REGION;

-- 4. Create Read-Only Application Role
CREATE ROLE IF NOT EXISTS DATAMIND_APP_ROLE;

-- Grant usage on Warehouse, Database, and Schema
GRANT USAGE ON WAREHOUSE DATAMIND_WH TO ROLE DATAMIND_APP_ROLE;
GRANT USAGE ON DATABASE DATAMIND_DB TO ROLE DATAMIND_APP_ROLE;
GRANT USAGE ON SCHEMA DATAMIND_DB.SALES TO ROLE DATAMIND_APP_ROLE;

-- Grant strictly SELECT privilege on all tables (No INSERT, UPDATE, DELETE, DROP)
GRANT SELECT ON ALL TABLES IN SCHEMA DATAMIND_DB.SALES TO ROLE DATAMIND_APP_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA DATAMIND_DB.SALES TO ROLE DATAMIND_APP_ROLE;

